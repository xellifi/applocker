  // ─── FCM ─────────────────────────────────────────────────────────────────

  /// Request notification permissions + get FCM token
  Future<String?> initFCM({required String deviceId}) async {
    try {
      final settings = await _fcm.requestPermission(
        alert: true,
        badge: true,
        sound: true,
      );
      debugPrint('//TEST: FCM permission: ${settings.authorizationStatus}');

      final token = await _fcm.getToken();
      debugPrint('//TEST: FCM token: $token');

      if (token != null && deviceId.isNotEmpty) {
        // Store FCM token in device doc for parent to send messages
        await _db.collection('devices').doc(deviceId).update({
          'fcmToken': token,
        });
      }

      // Token refresh
      _fcm.onTokenRefresh.listen((newToken) async {
        debugPrint('//TEST: FCM token refreshed');
        if (deviceId.isNotEmpty) {
          await _db.collection('devices').doc(deviceId).update({
            'fcmToken': newToken,
          });
        }
      });

      return token;
    } catch (e) {
      debugPrint('//TEST: initFCM error: $e');
      return null;
    }
  }

  /// Send FCM command from parent to child device
  /// Commands: 'show_overlay', 'hide_overlay', 'force_unlock'
  /// Uses Firestore as the command relay (no server-side FCM needed)
  Future<void> sendCommand({
    required String deviceId,
    required String command, // 'show_overlay' | 'hide_overlay' | 'force_unlock'
  }) async {
    try {
      await _db.collection('devices').doc(deviceId).update({
        'pendingCommand': command,
        'commandTimestamp': FieldValue.serverTimestamp(),
      });

      // Also update locked state
      if (command == 'show_overlay') {
        await setDeviceLocked(deviceId, true);
      } else if (command == 'hide_overlay' || command == 'force_unlock') {
        await setDeviceLocked(deviceId, false);
      }

      debugPrint('//TEST: Command sent: $command to $deviceId');
    } catch (e) {
      debugPrint('//TEST: sendCommand error: $e');
      rethrow;
    }
  }

