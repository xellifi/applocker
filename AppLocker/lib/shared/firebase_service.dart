  /// Sign up with email/password and store role in Firestore
  Future<UserCredential?> signUp({
    required String email,
    required String password,
    required String role, // 'parent' or 'child'
  }) async {
    try {
      final cred = await _auth.createUserWithEmailAndPassword(
        email: email,
        password: password,
      );
      // Store user role
      await _db.collection('users').doc(cred.user!.uid).set({
        'email': email,
        'role': role,
        'createdAt': FieldValue.serverTimestamp(),
      });
      debugPrint('//TEST: SignUp OK uid=${cred.user!.uid} role=$role');
      return cred;
    } on FirebaseAuthException catch (e) {
      debugPrint('//TEST: SignUp error: ${e.code} - ${e.message}');
      rethrow;
    } catch (e) {
      debugPrint('//TEST: SignUp unexpected error: $e');
      rethrow;
    }
  }

  /// Sign in with email/password
  Future<UserCredential?> signIn({
    required String email,
    required String password,
  }) async {
    try {
      final cred = await _auth.signInWithEmailAndPassword(
        email: email,
        password: password,
      );
      debugPrint('//TEST: SignIn OK uid=${cred.user!.uid}');

      // Ensure user document exists (upsert)
      final uid = cred.user!.uid;
      final doc = await _db.collection('users').doc(uid).get();
      if (!doc.exists) {
        await _db.collection('users').doc(uid).set({
          'email': email,
          'role': 'parent',
          'plan': 'trial',
          'createdAt': FieldValue.serverTimestamp(),
        });
        debugPrint('//TEST: Created missing user doc for $uid');
      }

      return cred;
    } on FirebaseAuthException catch (e) {
      debugPrint('//TEST: SignIn error: ${e.code} - ${e.message}');
      rethrow;
    }
  }

