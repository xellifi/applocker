          .collection('devices')
          .doc(deviceId)
          .collection('messages')
          .where('sender', isEqualTo: otherSender)
          .where('read', isEqualTo: false)
          .get();
      final batch = _db.batch();
      for (final doc in unread.docs) {
        batch.update(doc.reference, {'read': true});
      }
      await batch.commit();
    } catch (e) {
      debugPrint('//TEST: markMessagesRead error: $e');
    }
  }
