  /// Stream devices based on admin role
  Stream<QuerySnapshot<Map<String, dynamic>>> streamAdminDevices() {
    final uid = _auth.currentUser?.uid;
    if (uid == null) return const Stream.empty();
    
    return _db.collection('users').doc(uid).snapshots().asyncExpand((userDoc) {
      if (!userDoc.exists) {
        return _db.collection('devices').where('parentUid', isEqualTo: uid).snapshots();
      }
      final role = userDoc.data()?['role'] ?? 'parent';
      if (role == 'super_admin') {
        return _db.collection('devices').snapshots();
      } else {
        return _db.collection('devices').where('parentUid', isEqualTo: uid).snapshots();
      }
    });
  }

