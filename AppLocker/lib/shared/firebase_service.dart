  /// Child App: Link to parent using a 6-digit code
  Future<String?> getParentUidByCode(String code) async {
    try {
      debugPrint('//TEST: Querying pairing_sessions for code: $code');
      final doc = await _db.collection('pairing_sessions').doc(code).get();
      if (!doc.exists) {
        debugPrint('//TEST: Pairing session NOT FOUND for code: $code');
        return null;
      }
      
      final data = doc.data()!;
      final expiresAt = data['expiresAt'] as Timestamp?;
      if (expiresAt != null && expiresAt.toDate().isBefore(DateTime.now())) {
        debugPrint('//TEST: Pairing session EXPIRED for code: $code');
        await doc.reference.delete();
        return null;
      }
      
      final parentUid = data['parentUid'] as String;
      debugPrint('//TEST: Pairing session VALID for code: $code (Parent: $parentUid)');
      
      // Delete after use
      await doc.reference.delete();
      return parentUid;
    } catch (e) {
      debugPrint('//TEST: getParentUidByCode error: $e');
      return null;
    }
  }


